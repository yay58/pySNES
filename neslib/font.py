def glyph_rows(art):
    """Encode 7x5 ASCII art into 8 bitmap row bytes (1px left margin)."""
    rows = []
    for line in art:
        byte = 0
        for i, pixel in enumerate(line):
            if pixel == '#':
                byte |= 0x80 >> (i + 1)
        rows.append(byte)
    rows.append(0)  # 8th row is always blank
    return rows


def glyph_tile(art):
    """Encode ASCII art into a 16-byte CHR tile (plane 1 empty)."""
    return bytes(glyph_rows(art)) + bytes(8)


def font_chr():
    """Build an 8KB CHR bank with the font tiles at their ASCII codes."""
    bank = bytearray(CHR_BANK_SIZE)
    for char, art in GLYPHS.items():
        offset = ord(char) * TILE_SIZE
        bank[offset : offset + TILE_SIZE] = glyph_tile(art)
    return bytes(bank)
